-- DOJI — 017: one renewal of the TradingView sign-in at a time
-- ───────────────────────────────────────────────────────────────────────────
-- A rotating OAuth server may treat a refresh token presented twice as stolen
-- and revoke the sign-in, and two callers can find the token stale in the same
-- second. So a renewal first takes this lease by a PATCH filtered on it being
-- empty or lapsed — the arbitration `balance` uses — and the loser waits for
-- the token the holder writes. A lease rather than a flag, because a holder
-- that dies mid-renewal must not block every renewal after it.
--
-- Safe to re-run.
-- ═══════════════════════════════════════════════════════════════════════════
alter table public.tradingview_auth add column if not exists refreshing_until timestamptz;
